/**
 * Global density scale, shared by fields, buttons, lists, table rows, toolbars and chips.
 * `default` is today's look; `comfortable` is one step tighter and `compact` two steps
 * (the Vuetify / Material scale — density never makes a component larger than `default`).
 */
export enum Density {
  default = 'default',
  comfortable = 'comfortable',
  compact = 'compact',
}
